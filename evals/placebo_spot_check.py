"""TASK: Examines the placebo removal rules on 50 real trials.
GRADING: Coverage (meaningful network graphs).

    uv run python evals/placebo_spot_check.py            # fetch 50 trials and write the review sheet
    uv run python evals/placebo_spot_check.py --offline  # rebuild the sheet from the saved trials

The 50 trials are placebo-controlled studies from ClinicalTrials.gov (any condition), saved to
`evals/placebo_spot_check.json` so the check can be repeated on exactly the same records.
Every intervention record of every trial is listed with what the rules decided. A reviewer reads
the list and records each wrong decision in `REVIEW` below; accuracy is computed from that.

What counts as correct: a record is KEPT if it names a specific drug or biological, and REMOVED
if it is a placebo, sham, vehicle or other control, a non-drug intervention, or unspecific care.
"""
import argparse
import asyncio
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.aggregate.network import _LAYERS, _Side  # noqa: E402
from app.ctgov.client import CtGovClient, _Stats  # noqa: E402
from app.ctgov.normalize import normalize_study  # noqa: E402
from app.registry import api_fields_for  # noqa: E402

HERE = Path(__file__).resolve().parent
SAVED = HERE / "placebo_spot_check.json"
SHEET = HERE / "placebo_spot_check.md"

# Decisions the reviewer judged wrong: (NCT id, intervention name) -> what is wrong with it.
# Filled in after reading the sheet. An empty dict means "not reviewed yet", not "all correct".
REVIEW: dict[tuple[str, str], str] = {
    ("NCT01014845", "Hepatitis B vaccine"): "a real vaccine used as the active control in an arm typed placebo; removed",
    ("NCT00269542", "Iron Folic Acid alone - Placebo"): "real supplements used as the control in an arm typed placebo; removed",
    ("NCT04672395", "SCB-2019 vaccine for Placebo"): "the real vaccine, given later to the placebo group; removed",
    ("NCT04636697", "Intramuscular vaccine"): "names no particular vaccine; kept (layer 4, the label model, exists for names like this)",
}
REVIEWED_BY = "Claude (the AI assistant that wrote the code), reading all 114 rows on 2026-10-12; not yet checked by a person"


async def fetch() -> list[dict]:
    client = CtGovClient()
    params = {
        "filter.advanced": "AREA[ArmGroupType]PLACEBO_COMPARATOR AND AREA[StudyType]INTERVENTIONAL",
        "pageSize": 50,
        "fields": ",".join(api_fields_for(["intervention"])),
        "sort": "EnrollmentCount:desc",
    }
    try:
        page = await client._get("/studies", params, _Stats())
    finally:
        await client.aclose()
    return page["studies"]


def decisions(studies: list[dict]) -> list[dict]:
    rows = []
    for study in studies:
        trial = normalize_study(study, ["intervention"])
        for record in trial.intervention_records:
            layer = _Side._removed_by(record.name, record.type, record.arm_types)
            rows.append(
                {
                    "nct_id": trial.nct_id,
                    "name": record.name,
                    "type": record.type,
                    "arms": [arm or "untyped" for arm in record.arm_types],
                    "decision": "removed" if layer else "kept",
                    "layer": layer,
                }
            )
    return rows


def write_sheet(rows: list[dict]) -> None:
    wrong = {key: reason for key, reason in REVIEW.items()}
    for row in rows:
        row["wrong"] = wrong.get((row["nct_id"], row["name"]))
    judged_wrong = [row for row in rows if row["wrong"]]
    kept = [row for row in rows if row["decision"] == "kept"]
    removed = [row for row in rows if row["decision"] == "removed"]
    lines = [
        "# Placebo and non-drug removal: spot-check on 50 trials",
        "",
        "Generated by `evals/placebo_spot_check.py` from `evals/placebo_spot_check.json`.",
        "",
        f"- Trials: {len({row['nct_id'] for row in rows})} placebo-controlled interventional studies (the 50 largest by enrollment).",
        f"- Intervention records: {len(rows)}; kept {len(kept)}, removed {len(removed)}.",
    ]
    for layer, text in _LAYERS.items():
        count = sum(row["layer"] == layer for row in rows)
        if count:
            lines.append(f"  - removed as {text}: {count}")
    if REVIEW or REVIEWED_BY:
        correct = len(rows) - len(judged_wrong)
        lines += [
            f"- Reviewed by: {REVIEWED_BY}.",
            f"- Decisions judged correct: {correct} of {len(rows)} ({100 * correct / len(rows):.1f}%).",
            f"  - wrongly kept (should have been removed): {sum(row['decision'] == 'kept' for row in judged_wrong)}",
            f"  - wrongly removed (a real drug was dropped): {sum(row['decision'] == 'removed' for row in judged_wrong)}",
        ]
    else:
        lines.append("- Not reviewed yet.")
    lines += ["", "| Trial | Intervention | Type | Arms it is given in | Decision | Judged |", "|---|---|---|---|---|---|"]
    for row in rows:
        decision = "kept" if row["decision"] == "kept" else f"removed ({_LAYERS[row['layer']]})"
        judged = f"**wrong**: {row['wrong']}" if row["wrong"] else ("ok" if REVIEW or REVIEWED_BY else "")
        name = row["name"].replace("|", "/")
        lines.append(f"| {row['nct_id']} | {name} | {row['type']} | {', '.join(row['arms']) or 'none listed'} | {decision} | {judged} |")
    SHEET.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--offline", action="store_true", help="use the saved trials instead of fetching")
    args = parser.parse_args()
    if args.offline:
        studies = json.loads(SAVED.read_text(encoding="utf-8"))
    else:
        studies = asyncio.run(fetch())
        SAVED.write_text(json.dumps(studies, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    rows = decisions(studies)
    write_sheet(rows)
    kept = sum(row["decision"] == "kept" for row in rows)
    print(f"{len(studies)} trials, {len(rows)} intervention records: {kept} kept, {len(rows) - kept} removed")
    print(f"wrote {SHEET}")


if __name__ == "__main__":
    main()
